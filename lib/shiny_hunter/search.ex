defmodule ShinyHunter.Search do
  @moduledoc """
  Searches a grid of initial seeds × advances for wild Pokémon that pass a
  filter. FireRed boots from a 16-bit seed, so the full grid is
  `0..0xFFFF` seeds times the advances the player is willing to wait.

  The grid is split into chunks of consecutive seeds; each chunk is plain,
  independent work, which is what lets `run/2` and `ShinyHunter.Hunt` spread
  it over every scheduler.
  """

  import Bitwise
  alias ShinyHunter.{Rng, Wild}

  defmodule Params do
    @moduledoc false
    defstruct tid: 0,
              sid: 0,
              area: :land,
              # bit n set = table slot n accepted
              slot_mask: 0xFFF,
              seeds: 0..0xFFFF,
              advances: 0..9_999,
              shiny_only: true,
              # bit n set = nature n accepted
              nature_mask: 0x1FFFFFF,
              # {hp, atk, def, spe, spa, spd}
              min_ivs: {0, 0, 0, 0, 0, 0},
              chunk_size: 64,
              max_matches_per_chunk: 200
  end

  @doc "Splits the seed range into `{first, last}` chunks."
  def chunks(%Params{seeds: first..last//1, chunk_size: size}) do
    for start <- first..last//size, do: {start, min(start + size - 1, last)}
  end

  @doc "Number of Pokémon generated by the whole grid."
  def total(%Params{seeds: seeds, advances: advances}),
    do: Range.size(seeds) * Range.size(advances)

  @doc """
  Searches one chunk. `on_seed` is called after each initial seed with the
  number of Pokémon generated for it, for progress reporting.
  Returns the first `max_matches_per_chunk` matches as `{seed, advance, mon}`
  tuples, plus whether later ones were dropped.
  """
  def search_chunk({first, last}, %Params{} = p, on_seed \\ fn _ -> :ok end) do
    from..to//1 = p.advances
    per_seed = to - from + 1

    {matches, count} =
      Enum.reduce(first..last//1, {[], 0}, fn seed, acc ->
        acc = scan(Rng.jump(seed, from), seed, from, to, p, acc)
        on_seed.(per_seed)
        acc
      end)

    {Enum.reverse(matches), count > p.max_matches_per_chunk}
  end

  defp scan(_state, _seed, advance, to, _p, acc) when advance > to, do: acc

  defp scan(state, seed, advance, to, p, {matches, count} = acc) do
    {slot, _level_roll, pid, iv1, iv2} = mon = Wild.generate(state, p.area)

    acc =
      cond do
        not match?(slot, pid, iv1, iv2, p) -> acc
        count < p.max_matches_per_chunk -> {[{seed, advance, mon} | matches], count + 1}
        true -> {matches, count + 1}
      end

    scan(Rng.next(state), seed, advance + 1, to, p, acc)
  end

  defp match?(slot, pid, iv1, iv2, p) do
    (not p.shiny_only or Wild.shiny?(pid, p.tid, p.sid)) and
      (p.slot_mask >>> slot &&& 1) == 1 and
      (p.nature_mask >>> rem(pid, 25) &&& 1) == 1 and
      ivs_at_least?(Wild.ivs(iv1, iv2), p.min_ivs)
  end

  defp ivs_at_least?({a, b, c, d, e, f}, {ma, mb, mc, md, me, mf}),
    do: a >= ma and b >= mb and c >= mc and d >= md and e >= me and f >= mf

  @doc """
  Runs the whole search and returns `{matches, elapsed_ms}`.
  `max_concurrency: 1` runs it sequentially, for comparison.
  """
  def run(%Params{} = p, opts \\ []) do
    concurrency = Keyword.get(opts, :max_concurrency, System.schedulers_online())
    started = System.monotonic_time(:millisecond)

    matches =
      p
      |> chunks()
      |> Task.async_stream(&search_chunk(&1, p),
        max_concurrency: concurrency,
        ordered: false,
        timeout: :infinity
      )
      |> Enum.flat_map(fn {:ok, {matches, _truncated}} -> matches end)

    {Enum.sort(matches), System.monotonic_time(:millisecond) - started}
  end
end
